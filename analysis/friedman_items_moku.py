def find_item_policy(ministry, item_name):
    ministry = str(ministry or "")
    item_name = str(item_name or "")
    sorted_policies = sorted(ITEM_POLICIES, key=lambda p: len(p["match"][1]), reverse=True)
    for p in sorted_policies:
        m_key, i_key = p["match"]
        if m_key == ministry and (i_key == "" or i_key in item_name):
            return p
    return None

def find_moku_override(ministry, moku_name):
    ministry = str(ministry or "")
    moku_name = str(moku_name or "")
    best = None
    best_len = -1
    for (m, kw, r, measure, reason) in MOKU_OVERRIDES:
        if m == ministry and kw in moku_name and len(kw) > best_len:
            best = (r, measure, reason)
            best_len = len(kw)
    return best

def load_moku(xlsx_path):
    wb = openpyxl.load_workbook(xlsx_path, data_only=True)
    ws = wb["一般会計 予定経費要求書（科目別内訳）"]

    rows = []
    unmatched = []
    current_ministry = None
    current_org = None
    current_kou_name = None
    current_policy = None

    for row in ws.iter_rows(min_row=2, values_only=True):
        a, b, c, d = row[0], row[1], row[2], row[3]
        name9 = row[9]   # 項名 (col J / index 9)
        name10 = row[10] # 目名 (col K / index 10)
        amt = row[11]

        # 所管ヘッダー
        if a:
            current_ministry = str(a).strip()
        # 組織ヘッダー
        if b and not c:
            current_org = str(b).strip()

        # 項レベル: col C設定, col D=None
        if c and not d:
            current_kou_name = str(name9).strip() if name9 else ""
            current_policy = find_item_policy(current_ministry, current_kou_name)

        # 目レベル: col D設定, col K(name10)に目名, col L(amt)に金額
        if d is not None and name10 is not None and amt and isinstance(amt, (int, float)) and amt > 0:
            moku_name = str(name10).strip()
            oku = round(amt / 100000)
            if oku <= 0:
                continue

            # 目名オーバーライドを先に確認
            override = find_moku_override(current_ministry, moku_name)
            if override:
                retain_ratio, measure, note = override
                pol = current_policy
                if pol and pol["f"]:
                    f_label = "・".join(FRIEDMAN[n] for n in pol["f"])
                else:
                    f_label = "（目名OV）"
            elif current_policy is not None:
                f_nums = current_policy["f"]
                retain_ratio = current_policy["r"]
                measure = current_policy["m"]
                note = current_policy["note"]
                f_label = "・".join(FRIEDMAN[n] for n in f_nums) if f_nums else "該当なし"
            else:
                f_label = "要精査"
                retain_ratio = 0.2
                measure = "要精査"
                note = "未分類"
                unmatched.append(f"{current_ministry} / {current_kou_name} / {moku_name}: {oku}億")

            rows.append({
                "所管": current_ministry,
                "組織": current_org or "",
                "項名": current_kou_name or "",
                "目名": moku_name,
                "元額_億円": oku,
                "フリードマン根拠": f_label,
                "残存割合": f"{retain_ratio*100:.0f}%",
                "残す額_億円": round(oku * retain_ratio),
                "削減額_億円": oku - round(oku * retain_ratio),
                "措置": measure,
                "理由": note,
            })

    wb.close()
    return rows, unmatched

