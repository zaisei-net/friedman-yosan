# ポリシーマッチ関数
def find_policy(ministry, item_name):
    ministry = str(ministry or "")
    item_name = str(item_name or "")
    # キーワードが長いものを優先
    sorted_policies = sorted(
        ITEM_POLICIES,
        key=lambda p: len(p["match"][1]),
        reverse=True
    )
    for p in sorted_policies:
        m_key, i_key = p["match"]
        if m_key == ministry and (i_key == "" or i_key in item_name):
            return p
    return None  # 未分類


def load_items(xlsx_path):
    wb = openpyxl.load_workbook(xlsx_path, data_only=True)
    ws = wb["一般会計 予定経費要求書（科目別内訳）"]

    items = []
    current_ministry = None
    current_org = None

    for row in ws.iter_rows(min_row=2, values_only=True):
        a, b, c, d = row[0], row[1], row[2], row[3]
        name9, name10 = row[9], row[10]
        amt = row[11]

        if a:
            current_ministry = str(a).strip()
        if b and not c:
            current_org = str(b).strip()

        # 項レベル: col[2] が設定されて col[3] がNone
        if c and not d and amt and isinstance(amt, (int, float)) and amt > 0:
            name = name9 or name10 or "(名称なし)"
            items.append({
                "所管": current_ministry,
                "組織": current_org or "",
                "項コード": c,
                "科目名": str(name).strip(),
                "元額_千円": amt,
            })

    return items


def main():
    print("Excelを読み込み中...")
    items = load_items(r"C:\Users\s1\projects\新しいフォルダー\r8_ippan.xlsx")
    print(f"科目数（項レベル）: {len(items)}")

    rows = []
    unmatched = []
    total_oku = 0
    total_retain = 0

    for it in items:
        ministry = it["所管"]
        item_name = it["科目名"]
        oku = round(it["元額_千円"] / 100000)
        total_oku += oku

        policy = find_policy(ministry, item_name)

        if policy is None:
            f_label = "要精査"
            retain_ratio = 0.2
            measure = "要精査"
            note = "未分類。精査後に分類。"
            unmatched.append(f"{ministry} / {item_name}: {oku}億")
        else:
            f_nums = policy["f"]
            retain_ratio = policy["r"]
            f_label = "・".join(FRIEDMAN[n] for n in f_nums) if f_nums else "該当なし"
            measure = policy["m"]
            note = policy["note"]

        retain = round(oku * retain_ratio)
        total_retain += retain

        rows.append({
            "所管": ministry,
            "組織": it["組織"],
            "科目名": item_name,
            "元額_億円": oku,
            "フリードマン根拠": f_label,
            "残存割合": f"{retain_ratio*100:.0f}%",
            "残す額_億円": retain,
            "削減額_億円": oku - retain,
            "措置": measure,
            "理由": note,
        })

    # 出力
    out = r"C:\Users\s1\projects\新しいフォルダー\friedman_items_r8.csv"
    fields = ["所管","組織","科目名","元額_億円","フリードマン根拠","残存割合","残す額_億円","削減額_億円","措置","理由"]
    with open(out, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in rows:
            w.writerow(r)
        w.writerow({"所管":"【合計】","元額_億円":total_oku,"残す額_億円":total_retain,"削減額_億円":total_oku-total_retain})

    GDP = 6_000_000
    print(f"\n=== 令和8年度 一般会計 フリードマン削減試算（科目別） ===")
    print(f"科目数（項）: {len(items)}")
    print(f"元の総額: {total_oku:,}億円（公式: 1,223,092億円）")
    print(f"残す額:   {total_retain:,}億円")
    print(f"削減額:   {total_oku-total_retain:,}億円")
    print(f"削減率:   {(total_oku-total_retain)/total_oku*100:.1f}%")
    print(f"GDP比:    {total_oku/GDP*100:.1f}% → {total_retain/GDP*100:.1f}%")

    if unmatched:
        print(f"\n未分類科目 ({len(unmatched)}件):")
        for u in unmatched[:20]:
            print(f"  {u}")

    print(f"\nCSV: {out}")

    # 所管別集計
    from collections import defaultdict
    by_min = defaultdict(lambda: {"元": 0, "残": 0})
    for r in rows:
        by_min[r["所管"]]["元"] += r["元額_億円"]
        by_min[r["所管"]]["残"] += r["残す額_億円"]
    print(f"\n{'所管':<14} {'元額(億)':<10} {'残(億)':<10} {'削%'}")
    print("-"*50)
    for m, v in sorted(by_min.items(), key=lambda x: -x[1]["元"]):
        cut = (v["元"]-v["残"])/v["元"]*100 if v["元"] else 0
        print(f"{m:<14} {v['元']:>9,} {v['残']:>9,} {cut:>5.0f}%")


if __name__ == "__main__":
    main()
