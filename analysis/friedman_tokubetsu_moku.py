def is_interaccount(name):
    return any(k in name for k in INTERACCOUNT_KEYWORDS)

def find_policy(tokkai, kan_name, moku_name):
    """(特別会計KW, 款名KW, 目名KW)の3段階マッチ。最長スコア優先"""
    matched = []
    for pol in POLICIES:
        t_kw, k_kw, m_kw = pol[0], pol[1], pol[2]
        if t_kw and t_kw not in tokkai:
            continue
        if k_kw and k_kw not in kan_name:
            continue
        if m_kw and m_kw not in moku_name:
            continue
        score = len(t_kw) + len(k_kw) + len(m_kw) * 2
        matched.append((score, pol))
    if matched:
        return max(matched, key=lambda x: x[0])[1]
    return None

