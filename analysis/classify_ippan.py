def classify_fallback(ministry, kou_name, moku_name):
    """KOU_FUNCに基づいて各（所管・項名・目名）に固有の理由を生成する。
    返り値: (cls_list, reason) または None"""
    best = None
    best_score = -1
    for kan, kou_kw, cls_list, func_desc in KOU_FUNC:
        if kan and kan not in ministry:
            continue
        if kou_kw and kou_kw not in kou_name:
            continue
        score = len(kan) + len(kou_kw) * 2
        if score > best_score:
            best_score = score
            best = (cls_list, func_desc)
    if best is None:
        return None
    cls_list, func_desc = best
    reason = _reason_for_moku(moku_name, func_desc, kou_name)
    return cls_list, reason

