def retain_rate_for_list(cls_list):
    """複数分類のリストから最大残存率を返す"""
    rates = []
    for c in cls_list:
        if c == "該当なし":
            rates.append(0.0)
        elif c.startswith("一部"):
            rates.append(0.5)
        else:
            rates.append(1.0)
    return max(rates) if rates else 0.0

def primary_cls(cls_list):
    """表示・集計用の代表分類（①-⑩優先 > 一部 > 該当なし）"""
    order = {"①":0,"②":1,"③":2,"④":3,"⑤":4,"⑥":5,"⑦":6,"⑧":7,"⑨":8,"⑩":9}
    solid = [c for c in cls_list if c in order]
    if solid:
        return min(solid, key=lambda x: order[x])
    ichibu = [c for c in cls_list if c.startswith("一部")]
    if ichibu:
        return ichibu[0]
    return "該当なし"

def find_class(ministry, kou_name, moku_name):
    matched = []
    for m_kw, k_kw, moku_kw, cls_list, reason in CLASSIFY:
        if m_kw and m_kw not in ministry:
            continue
        if k_kw and k_kw not in kou_name:
            continue
        if moku_kw and moku_kw not in moku_name:
            continue
        score = len(m_kw) + len(k_kw) + len(moku_kw) * 2
        matched.append((score, cls_list, reason))
    if matched:
        best = max(matched, key=lambda x: x[0])
        return best[1], best[2]
    return ["未分類"], ""

