def retain_rate_for_list(cls_list):
    rates = []
    for c in cls_list:
        if c == "該当なし":
            rates.append(0.0)
        elif c.startswith("一部"):
            rates.append(0.5)
        else:
            rates.append(1.0)
    return max(rates) if rates else 0.0

def primary_cls(cls_list):
    order = {"①":0,"②":1,"③":2,"④":3,"⑤":4,"⑥":5,"⑦":6,"⑧":7,"⑨":8,"⑩":9}
    solid = [c for c in cls_list if c in order]
    if solid:
        return min(solid, key=lambda x: order[x])
    ichibu = [c for c in cls_list if c.startswith("一部")]
    if ichibu:
        return ichibu[0]
    return "該当なし"

def find_class(ministry, kou_name, moku_name):
    matched = []
    for m_kw, k_kw, moku_kw, cls_list, reason in CLASSIFY:
        if m_kw and m_kw not in ministry:
            continue
        if k_kw and k_kw not in kou_name:
            continue
        if moku_kw and moku_kw not in moku_name:
            continue
        score = len(m_kw) + len(k_kw) + len(moku_kw) * 2
        matched.append((score, len(moku_kw), len(k_kw), cls_list, reason))
    if matched:
        best = max(matched, key=lambda x: x[0])
        best_moku_len = best[1]
        best_kou_len  = best[2]
        if best_moku_len == 0:
            # 目名KWが空 → fallbackで分類・理由を両方置換
            fb = classify_fallback(ministry, kou_name, moku_name)
            if fb is not None:
                return fb
        elif best_kou_len == 0:
            # 項名KWが空・目名KWは非空 → 分類はCLASSIFYを維持し理由だけfallbackで生成
            fb = classify_fallback(ministry, kou_name, moku_name)
            if fb is not None:
                return best[3], fb[1]
        return best[3], best[4]
    fb = classify_fallback(ministry, kou_name, moku_name)
    if fb is not None:
        return fb
    return ["該当なし"], "いずれのフリードマン役割にも対応する市場の失敗を実証できない"

